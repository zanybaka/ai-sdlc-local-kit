"""Facade for the ai-task internals.

`scripts/ai-task.py` is a thin shim; everything lives in this package, split
by domain. This module re-exports every public name eagerly so `ai_task` is
the single import surface: tests reach it through `tests/ai_task_loader.py`,
and the CLI shells live in `ai_task.cli`.

The stdlib singletons at the end of the import list are part of the test
surface (`at.shutil`, `at.subprocess`, `at.sys`, `at.urlrequest`,
`at.urlerror`): tests patch attributes on those module objects directly.
"""

