#!/usr/bin/env python3
"""Telegram notifier hook for Claude Code (global, all repos).

Hook mode  (stdin):             read payload → write /tmp → spawn background → approve immediately.
Background mode (--background): parse transcript, git, quota → send Telegram → cleanup.

Never blocks the Stop event.
"""

from __future__ import annotations

import html
import json
import os
import re
import subprocess
import sys
import time
from pathlib import Path

# ── config ────────────────────────────────────────────────────────────────────

CLAUDE_DIR = Path.home() / ".claude"
ENV_FILE = CLAUDE_DIR / "channels" / "telegram" / ".env"
ACCESS_FILE = CLAUDE_DIR / "channels" / "telegram" / "access.json"

WRITE_TOOLS = frozenset({"Edit", "MultiEdit", "Write", "NotebookEdit"})
MAX_TRANSCRIPT_LINE = 10_000_000
MAX_REQUEST_CHARS = 80
MAX_COMPLETED_SHOWN = 4
QUOTA_STALE_AFTER_MIN = 20  # quota snapshot older than this shows its age in the line

# BACKLOG.md checkbox patterns. Shared so the open-count logic in
# backlog_stats and backlog_fully_delivered cannot drift apart.
OPEN_TASK_RE = re.compile(r"^\- \[ \]", re.MULTILINE)  # - [ ] open
CLOSED_TASK_RE = re.compile(
    r"^\- \[[x~]\]", re.MULTILINE
)  # - [x] done / - [~] deferred

# File-per-task store: in a migrated repo the root BACKLOG.md is
# a generated index and the task blocks live one-per-file in backlog/tasks/.
# This hook is global and dependency-free, so it does not import the canonical
# parser; it reads the layout convention instead: the FIRST checkbox line of a
# task file is that task's status.
TASKS_DIR_REL = "backlog/tasks"
CHECKBOX_STATUS_RE = re.compile(r"^\- \[([ x~])\]")
DIFF_TASK_ID_RE = re.compile(r"\[?([A-Z][A-Z0-9]+-\d+)")


def _task_file_statuses(cwd: Path) -> list[str]:
    """First-checkbox status per backlog/tasks/*.md; [] when not migrated."""
    tasks_dir = cwd / TASKS_DIR_REL
    if not tasks_dir.is_dir():
        return []
    statuses: list[str] = []
    for path in sorted(tasks_dir.glob("*.md")):
        try:
            text = path.read_text(encoding="utf-8")
        except OSError:
            continue
        for line in text.splitlines():
            m = CHECKBOX_STATUS_RE.match(line)
            if m:
                statuses.append(m.group(1))
                break
    return statuses


# ── telegram ──────────────────────────────────────────────────────────────────


def load_config() -> tuple[str | None, str | None]:
    token = None
    if ENV_FILE.is_file():
        for line in ENV_FILE.read_text(encoding="utf-8").splitlines():
            if line.startswith("TELEGRAM_BOT_TOKEN="):
                token = line.split("=", 1)[1].strip()
    chat_id = None
    if ACCESS_FILE.is_file():
        try:
            data = json.loads(ACCESS_FILE.read_text(encoding="utf-8"))
            allow = data.get("allowFrom", [])
            if allow:
                chat_id = allow[0]
        except (OSError, ValueError):
            pass
    return token, chat_id


def send_telegram(token: str, chat_id: str, text: str) -> None:
    # Hard kill-switch honored by tests (shared with scripts/ai-task.py) so a
    # test run never POSTs to the operator's real channel.
    if os.environ.get("AI_TASK_NOTIFY_DISABLED"):
        return
    import urllib.request

    url = f"https://api.telegram.org/bot{token}/sendMessage"
    payload = json.dumps(
        {"chat_id": chat_id, "text": text, "parse_mode": "HTML"}
    ).encode()
    req = urllib.request.Request(
        url, data=payload, headers={"Content-Type": "application/json"}
    )
    try:
        # Semgrep dynamic-urllib is a false positive: the URL is built from the literal https base and nothing else, file:// cannot get here.
        # nosemgrep: dynamic-urllib-use-detected
        urllib.request.urlopen(req, timeout=10)  # noqa: S310 - literal https Telegram API URL.
    except Exception:  # noqa: S110 - a failed notification must never break the session.
        pass


# ── transcript ────────────────────────────────────────────────────────────────


_INJECTED_USER_PREFIXES = (
    "this session is being continued from a previous conversation",
    "caveat: the messages below were generated by the user while running",
    "<command-name>",
    "<command-message>",
    "<command-args>",
    "<local-command-stdout>",
    "<local-command-stderr>",
    "<system-reminder>",
    "<task-notification>",
    "[request interrupted by user",
    "stop hook feedback",
    # ai-task headless run prompt — the machine packet header, not a human ask.
    # For ai-task runs the real title comes from the run record (see
    # _build_ai_task_stop_message); this stops the packet header leaking as the
    # request line on any fallback path.
    "# ai-task packet",
)


def _is_injected_user_text(text: str) -> bool:
    head = text.lstrip().lower()
    return any(head.startswith(p) for p in _INJECTED_USER_PREFIXES)


def parse_transcript(
    path: str | None,
) -> tuple[str | None, str | None, str | None, str | None, bool]:
    """Return (first_user_msg, last_user_msg, first_ts, last_ts, has_file_edits)."""
    if not path:
        return None, None, None, None, False
    first_user: str | None = None
    last_user: str | None = None
    first_ts: str | None = None
    last_ts: str | None = None
    has_edits = False
    try:
        with open(path, encoding="utf-8", errors="replace") as fh:
            for raw in fh:
                if not raw.strip() or len(raw) > MAX_TRANSCRIPT_LINE:
                    continue
                try:
                    entry = json.loads(raw)
                except ValueError:
                    continue
                if not isinstance(entry, dict):
                    continue
                ts = entry.get("timestamp")
                if isinstance(ts, str) and ts:
                    if first_ts is None:
                        first_ts = ts
                    last_ts = ts
                msg = entry.get("message")
                if not isinstance(msg, dict):
                    continue
                if msg.get("role") == "user":
                    content = msg.get("content")
                    text: str | None = None
                    if isinstance(content, str):
                        text = content.strip()
                    elif isinstance(content, list):
                        for block in content:
                            if isinstance(block, dict) and block.get("type") == "text":
                                t = block.get("text", "").strip()
                                if t:
                                    text = t
                                    break
                    if text and not _is_injected_user_text(text):
                        if first_user is None:
                            first_user = text
                        last_user = text
                if not has_edits:
                    content = msg.get("content")
                    if isinstance(content, list):
                        for item in content:
                            if (
                                isinstance(item, dict)
                                and item.get("type") == "tool_use"
                                and item.get("name") in WRITE_TOOLS
                            ):
                                has_edits = True
                                break
    except OSError:
        pass
    return first_user, last_user, first_ts, last_ts, has_edits


def duration_str(first_ts: str | None, last_ts: str | None) -> str | None:
    if not first_ts or not last_ts:
        return None
    try:
        from datetime import datetime

        def parse(ts: str) -> datetime:
            return datetime.fromisoformat(ts.replace("Z", "+00:00"))

        minutes = int((parse(last_ts) - parse(first_ts)).total_seconds() / 60)
        if minutes < 1:
            return "<1 мин"
        if minutes < 60:
            return f"{minutes} мин"
        h, m = divmod(minutes, 60)
        return f"{h}ч {m}м" if m else f"{h}ч"
    except Exception:
        return None


# ── git / backlog ──────────────────────────────────────────────────────────────


def git_branch(cwd: Path) -> str | None:
    try:
        r = subprocess.run(
            ["git", "rev-parse", "--abbrev-ref", "HEAD"],
            cwd=cwd,
            capture_output=True,
            text=True,
            timeout=5,
            check=False,
        )
        return r.stdout.strip() or None
    except Exception:
        return None


def backlog_stats(cwd: Path, session_start_ts: str | None) -> dict:
    """Return {completed: [id, ...], new_tasks: int, open: int}."""
    result: dict = {"completed": [], "new_tasks": 0, "open": 0}
    backlog = cwd / "BACKLOG.md"
    if not backlog.is_file():
        return result

    file_statuses = _task_file_statuses(cwd)
    if file_statuses:
        result["open"] = sum(1 for s in file_statuses if s == " ")
    else:
        try:
            text = backlog.read_text(encoding="utf-8")
            result["open"] = len(OPEN_TASK_RE.findall(text))
        except OSError:
            pass

    if not session_start_ts:
        return result

    try:
        log = subprocess.run(
            ["git", "log", "--format=%H", f"--before={session_start_ts}", "-1"],
            cwd=cwd,
            capture_output=True,
            text=True,
            timeout=5,
            check=False,
        )
        base = log.stdout.strip()
        if not base:
            return result
        # A migrated repo flips the checkbox in backlog/tasks/<ID>.md AND in
        # the regenerated index, so ids are de-duplicated across both paths.
        diff = subprocess.run(
            ["git", "diff", base, "--", "BACKLOG.md", TASKS_DIR_REL],
            cwd=cwd,
            capture_output=True,
            text=True,
            timeout=5,
            check=False,
        )
        completed: list[str] = []
        new_ids: list[str] = []
        unidentified_new = 0
        for line in diff.stdout.splitlines():
            if line.startswith("+- [x]"):
                raw = line[6:].strip()
                m = re.match(r"\*{0,2}\[?([A-Z][A-Z0-9]+-\d+)\]?\*{0,2}", raw)
                completed.append(m.group(1) if m else raw[:50])
            elif line.startswith("+- [ ]"):
                m = DIFF_TASK_ID_RE.match(line[6:].strip())
                if m:
                    new_ids.append(m.group(1))
                else:
                    unidentified_new += 1
        result["completed"] = list(dict.fromkeys(completed))
        result["new_tasks"] = len(dict.fromkeys(new_ids)) + unidentified_new
    except Exception:  # noqa: S110 - best-effort diff summary; an unreadable diff reports nothing.
        pass

    return result


def backlog_fully_delivered(cwd: Path) -> bool:
    """True when the backlog store has zero open tasks and ≥1 closed task.

    The closed-task clause guards against a false finish on an empty or
    template backlog with no tasks at all (open == 0 trivially). A repo with
    no BACKLOG.md is never "delivered" — there is nothing to finish. In a
    migrated repo the per-task files are the store; the
    generated index is not consulted.
    """
    backlog = cwd / "BACKLOG.md"
    if not backlog.is_file():
        return False
    file_statuses = _task_file_statuses(cwd)
    if file_statuses:
        return " " not in file_statuses
    try:
        text = backlog.read_text(encoding="utf-8")
    except OSError:
        return False
    return not OPEN_TASK_RE.search(text) and bool(CLOSED_TASK_RE.search(text))


# ── ai-task awareness ───────────────────────────────────────────────────────────
#
# Teamlead runs fire this hook from inside an ISOLATED git worktree at
# <main-repo>/.ai-task/worktrees/<run-id>. Two consequences the helpers below
# correct: (1) a worktree's `.git` is a FILE (a gitdir pointer), so the old
# "walk up to the first dir containing .git" stopped INSIDE the worktree and
# never reached the real repo's .ai-task — silently dropping the quota line and
# the 🏁 lease guard for every worktree run. (2) cwd.name is the opaque run-id
# dir, not the project. We resolve the real repo root and read the run's own
# record from the main-repo state.json (the worktree dir name IS the run id).

_WORKTREE_MARKER = "/.ai-task/worktrees/"


def _resolve_main_repo(cwd: Path) -> Path:
    """Real repo root, even when cwd is an ai-task worktree.

    Cheapest first: the literal worktrees path segment; then git's own
    `--git-common-dir` (whose parent is the main worktree root for both a linked
    worktree and a normal checkout); fall back to cwd.
    """
    s = str(cwd)
    if _WORKTREE_MARKER in s:
        return Path(s.split(_WORKTREE_MARKER, 1)[0])
    try:
        r = subprocess.run(
            ["git", "-C", str(cwd), "rev-parse", "--git-common-dir"],
            capture_output=True,
            text=True,
            timeout=5,
            check=False,
        )
        common = r.stdout.strip()
        if r.returncode == 0 and common:
            p = Path(common)
            if not p.is_absolute():
                p = (cwd / p).resolve()
            return p.parent
    except Exception:  # noqa: S110 - the cwd fallback below is the answer when git cannot say.
        pass
    return cwd


def _ai_task_file(cwd: Path, name: str) -> Path | None:
    """Locate <main-repo>/.ai-task/<name>, worktree-aware."""
    f = _resolve_main_repo(cwd) / ".ai-task" / name
    if f.is_file():
        return f
    # Fallback walk for a non-worktree subdir where git resolution failed.
    # `.is_dir()` (not `.exists()`) so a worktree's `.git` FILE never stops us.
    for parent in [cwd, *cwd.parents]:
        cand = parent / ".ai-task" / name
        if cand.is_file():
            return cand
        if (parent / ".git").is_dir():
            break
    return None


def _ai_task_run_record(cwd: Path) -> dict | None:
    """The ai-task run record for THIS run when cwd is a worktree, else None.

    The worktree dir name is the run id; look it up in the main-repo state.json.
    """
    s = str(cwd)
    if _WORKTREE_MARKER not in s:
        return None
    run_id = s.split(_WORKTREE_MARKER, 1)[1].split("/", 1)[0]
    state = _ai_task_file(cwd, "state.json")
    if not state:
        return None
    try:
        runs = json.loads(state.read_text(encoding="utf-8")).get("runs")
    except (OSError, ValueError):
        return None
    rec = runs.get(run_id) if isinstance(runs, dict) else None
    return rec if isinstance(rec, dict) else None


def _ai_task_wave(cwd: Path, task_id: str = "") -> tuple[int, int] | None:
    """(in_flight, total) for the current wave from state.json, or None.

    total = ids in the planned `last_batch`; in_flight = those still leased.
    Returns None when this task is not part of `last_batch` — that batch is then
    from an earlier wave and its counts are stale for this run.
    """
    state = _ai_task_file(cwd, "state.json")
    if not state:
        return None
    try:
        data = json.loads(state.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    batch = data.get("last_batch")
    if not isinstance(batch, list) or not batch:
        return None
    if task_id and task_id not in batch:
        return None
    leases = data.get("leases")
    leased = set(leases) if isinstance(leases, dict) else set()
    in_flight = sum(1 for t in batch if t in leased)
    return in_flight, len(batch)


def _clean_gate(g: str) -> str:
    """`risk-keyword:contract` → `contract`, `high-priority:P1` → `P1`."""
    return g.split(":", 1)[1] if ":" in g else g


def ai_task_run_active(cwd: Path) -> bool:
    """True when an `.ai-task` orchestrated run is currently in flight.

    Reads the main-repo `.ai-task/state.json` (worktree-aware) and reports
    whether its top-level `leases` map is non-empty — a leased run means work
    continues, so the caller should not claim the backlog is finished.

    `review_queue` is deliberately NOT consulted: it is not cleared on run
    completion (one repo carried 240 stale entries), so a non-empty queue does
    not mean work is pending. Do not "fix" this by re-adding that check.
    """
    state = _ai_task_file(cwd, "state.json")
    if not state:
        return False
    try:
        data = json.loads(state.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return False
    leases = data.get("leases")
    return bool(isinstance(leases, dict) and leases)


# ── quota ──────────────────────────────────────────────────────────────────────


def _humanize_age(minutes: int) -> str:
    if minutes < 60:
        return f"{minutes}м"
    if minutes < 1440:
        return f"{round(minutes / 60)}ч"
    return f"{round(minutes / 1440)}д"


def _quota_time_tag(captured: str, resets: str | None) -> str:
    """Build the ' (обн. HH:MM[, N назад][, окно сброшено])' suffix in LOCAL time.

    The snapshot stores UTC ISO timestamps. The old code printed the raw UTC
    hour via a `T(\\d{2}:\\d{2})` regex, so a 7-min-old OAuth refresh showed as
    '21:08' for a UTC+3 user and looked ~3h stale — which in turn made the
    (correct) percentage look like garbage. Convert to the local wall clock,
    and surface the snapshot's real age once it crosses QUOTA_STALE_AFTER_MIN so
    a genuinely old number is never presented as if it were current.
    """
    if not captured:
        return ""
    try:
        from datetime import datetime, timezone

        def _parse(ts: str) -> datetime:
            dtv = datetime.fromisoformat(ts.replace("Z", "+00:00"))
            return dtv.replace(tzinfo=timezone.utc) if dtv.tzinfo is None else dtv

        cap = _parse(captured)
        now = datetime.now(timezone.utc)
        local_hhmm = cap.astimezone().strftime("%H:%M")
        age_min = max(0, int((now - cap).total_seconds() // 60))
    except Exception:
        return ""

    tag = f" (обн. {local_hhmm}"
    if age_min >= QUOTA_STALE_AFTER_MIN:
        tag += f", {_humanize_age(age_min)} назад"
    # If the window's reset time has already passed, `used_percentage` describes
    # a window that no longer exists — say so rather than imply it is live.
    if resets:
        try:
            if now >= _parse(resets):
                tag += ", окно сброшено"
        except Exception:  # noqa: S110 - an unparsable reset time just omits the suffix.
            pass
    return tag + ")"


def quota_str(cwd: Path) -> str | None:
    snap = _ai_task_file(cwd, "quota-snapshot.json")
    if not snap:
        return None
    try:
        data = json.loads(snap.read_text(encoding="utf-8"))
        fh = data.get("windows", {}).get("five_hour", {})
        used = fh.get("used_percentage")
        captured = fh.get("captured_at", data.get("captured_at", ""))
        resets = fh.get("resets_at")
        if used is not None:
            remaining = 100 - float(used)
            return f"5h: {remaining:.0f}% ост.{_quota_time_tag(captured, resets)}"
    except Exception:  # noqa: S110 - a missing or malformed snapshot means no quota tag.
        pass
    return None


# ── message builders ───────────────────────────────────────────────────────────


def _truncate_request(text: str) -> str:
    line = text.splitlines()[0] if text else ""
    return (line[:MAX_REQUEST_CHARS] + "…") if len(line) > MAX_REQUEST_CHARS else line


def _build_ai_task_stop_message(
    project: str, run: dict, cwd: Path, duration: str | None, quota: str | None
) -> str:
    """Stop ping for an ai-task worktree run.

    This fires from inside the headless `claude -p` when the model stops —
    BEFORE ai-task runs verify/review/verdict — so it headlines the real task
    title, backend/size/risk, and wave context, but deliberately never claims a
    verify or verdict outcome (those don't exist yet; the ai-task finalize ping
    carries them). The emoji is 🔨 (implementation done, verification ahead).
    """
    # parse_mode=HTML: escape every data value, or a title with <, >, & makes
    # Telegram silently drop the message.
    task_id = str(run.get("task_id") or "?")
    title = run.get("task_title") or ""

    header = f"🔨 <b>{html.escape(project)}</b> · {html.escape(task_id)}"
    if duration:
        header += f" · {html.escape(duration)}"
    parts = [header]
    if title:
        parts.append(f"<i>«{html.escape(_truncate_request(title))}»</i>")

    meta = []
    backend = run.get("backend")
    if backend:
        meta.append(f"backend {html.escape(str(backend))}")
    size = run.get("telemetry_size")
    if size:
        meta.append(html.escape(str(size)))
    gates = [_clean_gate(g) for g in run.get("review_gates") or [] if isinstance(g, str)]
    if gates:
        meta.append(f"⚠ риск: {html.escape(', '.join(gates))}")
    if meta:
        parts.append(" · ".join(meta))

    parts.append("реализация готова · проверка впереди")

    wave = _ai_task_wave(cwd, task_id)
    if wave:
        in_flight, total = wave
        done = max(0, total - in_flight)
        parts.append(f"волна: {done}/{total} готово · {in_flight} в работе")

    if quota:
        parts.append(f"◈ {quota}")
    return "\n\n".join(parts)


def build_stop_message(data: dict) -> str:
    cwd = Path(data.get("cwd") or ".")
    main_root = _resolve_main_repo(cwd)
    project = main_root.name or cwd.name or "?"
    first_user, last_user, first_ts, last_ts, _ = parse_transcript(
        data.get("transcript_path")
    )

    # Baseline = the last ping (per-task delta). First ping → session start, but
    # only if recent; an old/continued session reports no duration or completed
    # diff instead of a misleading multi-day total.
    session_id = data.get("session_id", "unknown")
    baseline_ts = last_ping_iso(session_id)
    if baseline_ts is None and _within_hours(
        first_ts, last_ts, MAX_SESSION_BASELINE_HOURS
    ):
        baseline_ts = first_ts

    duration = duration_str(baseline_ts, last_ts)
    quota = quota_str(cwd)

    # An ai-task worktree run → headline the real task + wave (pre-finalize),
    # not the worktree dir name + frozen single-task backlog snapshot.
    run = _ai_task_run_record(cwd)
    if run is not None:
        return _build_ai_task_stop_message(project, run, cwd, duration, quota)

    # Interactive / in-tree session → backlog-diff summary as before.
    branch = git_branch(cwd)
    bl = backlog_stats(cwd, baseline_ts)

    # 🏁 only when every backlog task is delivered AND no ai-task run is still
    # leased; otherwise ✅ (work continues, or this repo has no backlog).
    finished = backlog_fully_delivered(cwd) and not ai_task_run_active(cwd)
    # parse_mode=HTML: escape data values (project/branch/request/ids).
    header = f"{'🏁' if finished else '✅'} <b>{html.escape(project)}</b>"
    if branch:
        header += f" · {html.escape(branch)}"
    if duration:
        header += f" · {html.escape(duration)}"

    parts = [header]

    request = last_user or first_user  # most recent request, not the stale first one
    if request:
        parts.append(f"<i>«{html.escape(_truncate_request(request))}»</i>")

    bl_lines = []
    if bl["completed"]:
        ids = html.escape(", ".join(bl["completed"][:MAX_COMPLETED_SHOWN]))
        extra = (
            f" (+{len(bl['completed']) - MAX_COMPLETED_SHOWN})"
            if len(bl["completed"]) > MAX_COMPLETED_SHOWN
            else ""
        )
        bl_lines.append(f"✓ {ids}{extra}")
    if bl["new_tasks"]:
        bl_lines.append(f"+ {bl['new_tasks']} новых задач")
    if bl["open"]:
        bl_lines.append(f"○ {bl['open']} открытых")
    if bl_lines:
        parts.append("\n".join(bl_lines))

    if quota:
        parts.append(f"◈ {quota}")

    return "\n\n".join(parts)


def build_notification_message(data: dict) -> str:
    cwd = Path(data.get("cwd") or ".")
    project = _resolve_main_repo(cwd).name or cwd.name or "?"
    first_user, last_user, _, _, _ = parse_transcript(data.get("transcript_path"))

    branch = git_branch(cwd)
    quota = quota_str(cwd)

    # parse_mode=HTML: escape every data value.
    header = f"🤖 <b>{html.escape(project)}</b>"
    if branch:
        header += f" · {html.escape(branch)}"

    parts = [header]
    request = last_user or first_user  # most recent request, not the stale first one
    if request:
        parts.append(f"<i>«{html.escape(_truncate_request(request))}»</i>")

    title = data.get("title", "")
    msg = data.get("message", "")
    if title:
        parts.append(f"<b>{html.escape(str(title))}</b>")
    if msg:
        parts.append(html.escape(str(msg)))

    if quota:
        parts.append(f"◈ {quota}")

    return "\n\n".join(parts)


# ── dedup ─────────────────────────────────────────────────────────────────────

# Coalesce bursts (e.g. a Notification + the Stop of the same turn) but still
# ping once per task: a fresh Stop only re-notifies when the last ping for this
# session was more than THROTTLE_SECONDS ago. Previously this was a one-shot
# per session, which silenced every task after the first in a long session.
THROTTLE_SECONDS = 25


def _flag(session_id: str) -> Path:
    return Path(f"/tmp/claude-tg-{session_id}.notified")


def already_notified(session_id: str) -> bool:
    flag = _flag(session_id)
    try:
        if not flag.exists():
            return False
        return (time.time() - flag.stat().st_mtime) < THROTTLE_SECONDS
    except OSError:
        return False


def mark_notified(session_id: str) -> None:
    try:
        _flag(session_id).touch()
    except OSError:
        pass


# Each ping reports the delta SINCE THE LAST PING (per task), not the cumulative
# span of a possibly multi-day / continued session — otherwise the header shows a
# bogus "71ч" duration and every task ever closed as "completed". The dedup flag's
# mtime is the last-ping time. On the FIRST ping there is no flag; fall back to the
# session start only if it is recent — a long-lived session's start is uselessly
# far back, so we omit duration + the completed-since diff rather than mislead.
MAX_SESSION_BASELINE_HOURS = 8


def last_ping_iso(session_id: str) -> str | None:
    """ISO-8601 (UTC) of the previous ping for this session, or None on first ping."""
    flag = _flag(session_id)
    try:
        if not flag.exists():
            return None
        from datetime import datetime, timezone

        return datetime.fromtimestamp(flag.stat().st_mtime, tz=timezone.utc).isoformat()
    except OSError:
        return None


def _within_hours(start_ts: str | None, end_ts: str | None, hours: float) -> bool:
    if not start_ts or not end_ts:
        return False
    try:
        from datetime import datetime

        def p(ts: str) -> datetime:
            return datetime.fromisoformat(ts.replace("Z", "+00:00"))

        return (p(end_ts) - p(start_ts)).total_seconds() < hours * 3600
    except Exception:
        return False


