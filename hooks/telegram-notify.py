def run_background(data_file: str) -> None:
    try:
        data = json.loads(Path(data_file).read_text(encoding="utf-8"))
    except Exception:
        return
    finally:
        try:
            Path(data_file).unlink(missing_ok=True)
        except Exception:  # noqa: S110 - scratch-file cleanup; a leftover temp file is harmless.
            pass

    token, chat_id = load_config()
    if not token or not chat_id:
        return

    session_id = data.get("session_id", "unknown")

    if "message" in data:
        text = build_notification_message(data)
        send_telegram(token, chat_id, text)
        mark_notified(session_id)
        return

    # ai-task sends its OWN authoritative outcome ping at verdict (Level B); when
    # that is enabled it exports AI_TASK_SUPPRESS_STOP_PING in the headless child
    # env so this hook does not double-ping. Gate on BOTH the env var AND this
    # actually being an ai-task worktree run, so a nested/interactive sub-session
    # that merely inherited the env var still pings. Unset → enriched ping below.
    if os.environ.get("AI_TASK_SUPPRESS_STOP_PING") and _ai_task_run_record(
        Path(data.get("cwd") or ".")
    ) is not None:
        return

    if already_notified(session_id):
        return
    _, _, _, _, has_edits = parse_transcript(data.get("transcript_path"))
    if not has_edits:
        return

    text = build_stop_message(data)
    send_telegram(token, chat_id, text)
    mark_notified(session_id)


def run_hook() -> None:
    try:
        data = json.load(sys.stdin)
    except Exception:
        json.dump({"decision": "approve"}, sys.stdout)
        return

    session_id = data.get("session_id", "unknown")
    data_file = f"/tmp/claude-tg-payload-{session_id}.json"

    try:
        Path(data_file).write_text(json.dumps(data), encoding="utf-8")
        subprocess.Popen(
            [sys.executable, str(Path(__file__).resolve()), "--background", data_file],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            start_new_session=True,
        )
    except Exception:  # noqa: S110 - the hook still approves when the notifier cannot start.
        pass

    json.dump({"decision": "approve"}, sys.stdout)


# ── entry ─────────────────────────────────────────────────────────────────────

if __name__ == "__main__":
    try:
        if len(sys.argv) >= 3 and sys.argv[1] == "--background":
            run_background(sys.argv[2])
        else:
            run_hook()
    except Exception:
        if "--background" not in sys.argv:
            json.dump({"decision": "approve"}, sys.stdout)
